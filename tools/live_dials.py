"""The dials the compositor pass reads: one table for the slider panel and DOOM's menu.

`live_dials.py` with a path argument writes the C table the game compiles in.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
# What `make doom` starts on when nobody has saved a look, and what the menu's reset returns to.
DOOM_LOOK = {"halation": 0.08, "glow": 0.15, "beam": 0.2, "glow_knee": 0.2}
# The offline renderer also has per-channel decay and rise controls that the pass lacks.
EXCLUDED = {"decay_r", "decay_g", "decay_b", "rise", "ghost_rise"}
EXTRA = (
    ("decay", "Phosphor fade", "Phosphor", 1, 400, 1, 50, "ms", "How long the light takes to fade"),
    ("core", "Flat middle", "Tube", 0, .95, .01, 0, "", "Keep the middle flat and bend toward the rim"),
    ("inset", "Safe edge", "Tube", 0, .12, .005, .06, "", "Draw the picture smaller inside the glass"),
    ("glow_knee", "Glow threshold", "Phosphor", 0, 1, .01, .02, "", "How bright a pixel must be before it glows"))
KEYS = ("name", "label", "group", "min", "max", "step", "default", "unit", "help")


def load():
    """(dials, presets) as the compositor pass understands them."""
    def read(name):
        return json.loads((ROOT / "tools" / name).read_text(encoding="utf-8"))
    dials = [d for d in read("dials.json") if d["name"] not in EXCLUDED]
    for row in EXTRA:
        if not any(d["name"] == row[0] for d in dials):
            dials.append(dict(zip(KEYS, row)))
    presets = {}
    for name, original in read("presets.json").items():
        values = dict(original)
        channels = [values.pop(k) for k in ("decay_r", "decay_g", "decay_b") if k in values]
        if channels:
            if len(channels) != 3 or len(set(channels)) != 1:
                continue  # the pass has one fade, so a preset with three cannot be honoured
            values["decay"] = channels[0]
        if values.pop("ghost_rise", 500) != 500:
            continue
        presets[name] = values
    return dials, presets


def menu_step(dial):
    """One press in the menu: about a fortieth of the range, in whole dial steps."""
    return max(1, round((dial["max"] - dial["min"]) / 40 / dial["step"])) * dial["step"]


def header():
    dials, presets = load()
    groups = list(dict.fromkeys(d["group"] for d in dials))
    quote = json.dumps
    out = ["// Generated by tools/live_dials.py from tools/dials.json and tools/presets.json.",
           "#define CRT_NUMPAGES %d" % len(groups),
           "#define CRT_NUMDIALS %d" % len(dials),
           "#define CRT_NUMPRESETS %d" % len(presets),
           "static const char *const crt_pages[CRT_NUMPAGES] = {%s};" % ", ".join(map(quote, groups)),
           "static const crt_dial_t crt_dials[CRT_NUMDIALS] = {"]
    for d in sorted(dials, key=lambda d: groups.index(d["group"])):
        step = ("%.6f" % d["step"]).rstrip("0").rstrip(".")
        decimals = len(step.partition(".")[2])
        out.append("    {%s, %s, %s, %d, %r, %r, %r, %r, %r, %d}," % (
            quote(d["name"]), quote(d["label"]), quote(d["unit"]), groups.index(d["group"]),
            float(d["min"]), float(d["max"]), float(menu_step(d)), float(d["default"]),
            float(DOOM_LOOK.get(d["name"], d["default"])), decimals))
    out += ["};", "static const crt_preset_t crt_presets[CRT_NUMPRESETS] = {"]
    for name, values in presets.items():
        out.append("    {%s, %s}," % (quote(name.split(" (")[0]),
                                      quote(",".join("%s=%r" % i for i in values.items()))))
    return "\n".join(out + ["};", ""])


if __name__ == "__main__":
    target = Path(sys.argv[1])
    text = header()
    if not target.exists() or target.read_text() != text:
        target.write_text(text)
